// Copies the shared rules code into the standalone tools in legacy/, between
// the "sheet converter" markers. Run after changing anything in src/:
//
//   node scripts/build-legacy.mjs
//
// The tools then still work on their own, straight from disk.

import { readFileSync, writeFileSync } from 'node:fs';
import { bundle, RULES_FILES } from './bundle.mjs';

const START = '/* ── sheet converter: generated by scripts/build-legacy.mjs from src/ — do not edit by hand ── */';
const END = '/* ── end sheet converter ── */';

// What each tool gets from the rules code
export const TARGETS = {
  'legacy/dm-helper.html': { SheetConverter: ['adapters/dm-helper', ['toDMHelper']] },
  'legacy/character-sheet.html': {
    SheetSpells: ['rules/spells', ['findSpell']],
    SheetScenarios: ['rules/scenarios', ['modNum', 'signed', 'ATTACK_TYPES', 'RATE_OPTIONS', 'scenarioRate', 'scenarioType',
      'scenarioSpell', 'scenarioAbility', 'activeEffectsFor', 'scenarioDamage', 'scenarioBreakdown', 'normalizeEffects', 'effectOption']],
    SheetRules: ['rules/weapons', ['PHB_WEAPONS']],
    SheetGuess: ['rules/migrate', ['guessCategory']],
  },
};
// Data a tool gets alongside the rules code, as window globals
const DATA = {
  'legacy/character-sheet.html': { SheetSpellCatalog: 'data/spell-catalog.json' },
  'legacy/dm-helper.html': { SheetSpellCatalog: 'data/spell-catalog.json' },
};

export function bundleFor(file) {
  const data = Object.entries(DATA[file] || {})
    .map(([name, path]) => `window.${name} = ${JSON.stringify(JSON.parse(readFileSync(path, 'utf8')))};`);
  return [bundle(RULES_FILES, { expose: TARGETS[file] }), ...data].join('\n');
}

if (import.meta.url === `file://${process.argv[1]}`) {
  for (const file of Object.keys(TARGETS)) {
    const html = readFileSync(file, 'utf8');
    const a = html.indexOf(START);
    const b = html.indexOf(END);
    if (a < 0 || b < a) {
      console.error(`Markers not found in ${file}`);
      process.exit(1);
    }
    writeFileSync(file, html.slice(0, a + START.length) + '\n' + bundleFor(file) + '\n' + html.slice(b));
    console.log(`Updated ${file}`);
  }
}
